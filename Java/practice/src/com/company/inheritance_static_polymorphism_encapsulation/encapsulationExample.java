package com.company.inheritance_static_polymorphism_encapsulation;

public class encapsulationExample {
    private int b;
    private int c;

    public int getB() {
        return b;
    }

    public void setB(int b) {
        this.b = b;
    }

    public int getC() {
        return c;
    }

    public void setC(int c) {
        this.c = c;
    }
}
